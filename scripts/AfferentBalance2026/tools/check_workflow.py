def check_docs(write=False):
    """Check generated bytes and source-document links; results links are explicitly optional."""
    generated=generated_references()
    for path,text in generated.items():
        if write:path.write_text(text)
        elif not path.exists() or path.read_text()!=text:
            raise ValueError(f'Stale generated reference: {path}; run --write-docs')
    documents=[*sorted((ROOT/'docs').glob('*.md')),ROOT/'README.md',ROOT/'README.en.md',ROOT/'STRUCT.en.md']
    links=0
    for path in documents:
        for target in re.findall(r'\]\(([^)]+)\)',path.read_text()):
            if '://' in target or target.startswith('#'):continue
            location=target.split('#')[0]
            if not location:continue
            if not (path.parent/location).exists():raise ValueError(f'Broken source link in {path}: {target}')
            links+=1
    return dict(generated=len(generated),documents=len(documents),source_links=links,status='passed')


def check_notebooks(log_directory):
    """Execute notebook code in smoke mode without changing JSON, outputs or notes."""
    os.environ['SPIKINGNN_NOTEBOOK_SMOKE']='1'
    os.environ['MPLBACKEND']='Agg'
    import matplotlib.pyplot as plt
    output=Path(log_directory);output.mkdir(parents=True,exist_ok=False)
    records=[]
    for path in sorted((ROOT/'experiments').glob('*/*.ipynb')):
        before=hashlib.sha256(path.read_bytes()).hexdigest()
        namespace={'__name__':'notebook_smoke'};count=0
        with (output/f'{path.parent.name}_{path.stem}.log').open('w') as stream, contextlib.redirect_stdout(stream),contextlib.redirect_stderr(stream):
            for index,cell in enumerate(read_json(path)['cells']):
                code=''.join(cell['source'])
                if cell['cell_type']=='code' and code.strip():
                    exec(compile(code,f'{path}:cell{index}','exec'),namespace);count+=1
            for name in ('live_pendulum','live_pendulum_activity'):
                if name in namespace:
                    view=namespace[name];view.controller.advance(5,.002);view._record();view._draw();view.close()
            plt.close('all')
        assert hashlib.sha256(path.read_bytes()).hexdigest()==before
        records.append(dict(notebook=str(path.relative_to(ROOT)),cells=count,status='passed'))
    (output/'summary.json').write_text(json.dumps(records,indent=2))
    return records


def profile_child(mode, output):
    """Measure the same candidates through old/new evaluators, including fresh JIT."""
    import pickle
    import numpy as np
    from scripts.AfferentBalance2026.experiments.core.config import resolve_config
    from scripts.AfferentBalance2026.experiments.core import run, artifacts
    cfg=resolve_config(ROOT/'configs/studies/A_smoke.json',overrides={'protocol':{'balance':{'duration_s':.05}}})
    task=run.make_task(cfg);units=np.tile(task.codec.initial(),(6,1));physical=np.array([task.codec.decode(u) for u in units])
    result={'mode':mode,'population':6,'duration_s':.05,'bank_counts':{k:len(v) for k,v in task.banks.items()},'cpu_count':os.cpu_count()}
    def evaluate(pool, bank):
        return pool.evaluate(physical,task.banks[bank],.05) if mode=='old' else pool.evaluate(units,bank)
    factory=(lambda workers:run.PopulationEvaluator(task.config.mechanics,workers)) if mode=='old' else (lambda workers:run.EvaluationPool(task,workers))
    with factory(1) as pool:
        start=time.perf_counter();scores,metrics=evaluate(pool,'training');result['cold_evaluation_s']=time.perf_counter()-start
        for bank in ('training','validation'):
            times=[]
            for _ in range(7):
                start=time.perf_counter();evaluate(pool,bank);times.append(time.perf_counter()-start)
            result['warm_'+bank+'_median_s']=float(np.median(times))
    result['metrics_sha256']=hashlib.sha256(metrics.tobytes()).hexdigest()
    with factory(2) as pool:
        start=time.perf_counter();evaluate(pool,'training');result['spawn_first_evaluation_s']=time.perf_counter()-start
        times=[]
        for _ in range(7):
            start=time.perf_counter();evaluate(pool,'training');times.append(time.perf_counter()-start)
        result['process_warm_median_s']=float(np.median(times))
    message=(physical[0],task.banks['training'],task.config.mechanics,.05,np.zeros((4,2))) if mode=='old' else (units[0],'training',0.)
    start=time.perf_counter()
    for _ in range(1000):packet=pickle.dumps(message)
    result.update(ipc_payload_bytes=len(packet),serialize_1000_s=time.perf_counter()-start)
    target=Path(output).with_suffix('.npz');times=[]
    for _ in range(5):
        start=time.perf_counter();artifacts.atomic_npz(target,normalized=units,physical=physical,training_scores=scores,training_metrics=metrics);times.append(time.perf_counter()-start)
    result['compressed_array_write_median_s']=float(np.median(times))
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    _,trace=run.simulate(physical[0],task.banks['training'][0],task.config.mechanics,duration_s=.05)
    start=time.perf_counter();fig,ax=plt.subplots();ax.plot(trace[:,0],trace[:,1]);fig.savefig(Path(output).with_suffix('.png'));plt.close(fig)
    result['plot_s']=time.perf_counter()-start
    Path(output).write_text(json.dumps(result,indent=2))


def profile(output):
    """Run independent cold-cache processes and retain evidence, not a speedup claim."""
    output=Path(output).resolve();output.mkdir(parents=True,exist_ok=False)
    results=[]
    for mode in ('old','new'):
        environment=dict(os.environ,OPENBLAS_NUM_THREADS='1',OMP_NUM_THREADS='1',NUMBA_CACHE_DIR=str(output/f'cache_{mode}'))
        subprocess.run([sys.executable,str(Path(__file__).resolve()),'--profile-child',mode,'--profile-output',str(output/f'{mode}.json')],
                       env=environment,check=True,cwd=repository)
        results.append(read_json(output/f'{mode}.json'))
    assert results[0]['metrics_sha256']==results[1]['metrics_sha256']
    (output/'comparison.json').write_text(json.dumps(results,indent=2))
    return results


def main():
    """Parse explicitly requested developer checks."""
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-docs',action='store_true')
    parser.add_argument('--check-docs',action='store_true')
    parser.add_argument('--notebooks',type=Path,help='New directory for smoke logs; notebooks are read-only.')
    parser.add_argument('--profile',type=Path,help='New directory for fixed-protocol timings.')
    parser.add_argument('--profile-child',choices=['old','new'],help=argparse.SUPPRESS)
    parser.add_argument('--profile-output',type=Path,help=argparse.SUPPRESS)
    args=parser.parse_args();results={}
    if args.profile_child:
        profile_child(args.profile_child,args.profile_output);return
    if args.write_docs or args.check_docs:results['docs']=check_docs(args.write_docs)
    if args.notebooks:results['notebooks']=check_notebooks(args.notebooks)
    if args.profile:results['profile']=profile(args.profile)
    print(json.dumps(results,ensure_ascii=False,indent=2))


if __name__=='__main__':main()
